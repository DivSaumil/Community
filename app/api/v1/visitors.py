@router.post("/daily-help", response_model=DailyHelpOut, dependencies=[Depends(admin_required)])
async def register_daily_help(payload: DailyHelpCreate, db: AsyncSession = Depends(get_db)):
    """Register daily help staff (maid, driver) and link to flats. Admin only."""
    # Verify all flat IDs exist
    for f_id in payload.flat_ids:
        flat_res = await db.execute(select(Flat).where(Flat.id == f_id))
        if not flat_res.scalar_one_or_none():
            raise HTTPException(status_code=400, detail=f"Flat {f_id} does not exist")
            
    db_help = await crud_visitors.create_daily_help(db, payload)
    
    # Return schema out format
    return {
        "id": db_help.id,
        "name": db_help.name,
        "phone": db_help.phone,
        "role": db_help.role,
        "pass_code": db_help.pass_code,
        "is_active": db_help.is_active,
        "created_at": db_help.created_at,
        "flats": [f"{f.block}-{f.flat_number}" for f in db_help.flats]
    }


