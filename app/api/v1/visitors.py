@router.post("/pre-approve", response_model=VisitorPassOut)
async def pre_approve_visitor(
    payload: VisitorPassCreate, 
    db: AsyncSession = Depends(get_db), 
    current_user: User = Depends(get_current_user)
):
    """Generate a pre-approved visitor pass. Accessible by residents and tenants."""
    # Verify resident lives in the flat
    flat_query = select(Flat).where(Flat.id == payload.flat_id)
    flat_res = await db.execute(flat_query)
    flat = flat_res.scalar_one_or_none()
    
    if not flat:
        raise HTTPException(status_code=404, detail="Flat not found")
        
    if current_user.role not in ["admin"] and flat.owner_id != current_user.id and flat.tenant_id != current_user.id:
        raise HTTPException(
            status_code=403,
            detail="You can only pre-approve visitors for flats where you reside",
        )
        
    return await crud_visitors.create_visitor_pass(db, payload, current_user.id)


